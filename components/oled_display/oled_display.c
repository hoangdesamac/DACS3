static void oled_write_cmd(uint8_t cmd)
{
    uint8_t data[2] = {0x00, cmd};
    i2c_master_transmit(dev_handle, data, 2, -1);
}

static void oled_write_data(const uint8_t *buf, size_t len)
{
    uint8_t data[256];

    while (len > 0)
    {
        size_t chunk_len = len;
        if (chunk_len > (sizeof(data) - 1))
        {
            chunk_len = sizeof(data) - 1;
        }

        data[0] = 0x40;
        memcpy(&data[1], buf, chunk_len);
        i2c_master_transmit(dev_handle, data, chunk_len + 1, -1);

        buf += chunk_len;
        len -= chunk_len;
    }
}

static void oled_draw_char(int x, int y, char c)
{

    if (x < 0 || x > OLED_WIDTH - 5 || y < 0 || y > OLED_HEIGHT - 8)
        return;

    int char_idx = c - 32;
    if (char_idx < 0 || char_idx >= 95)
        return;

    int page = y / 8;
    int bit_pos = y % 8;

    for (int i = 0; i < 5; i++)
    {
        uint8_t char_data = font_5x7[char_idx][i];

        display_buffer[page][x + i] |= (char_data << bit_pos);

        if (page + 1 < OLED_PAGES && bit_pos > 0)
        {
            display_buffer[page + 1][x + i] |= (char_data >> (8 - bit_pos));
        }
    }
}

static void oled_draw_string(int x, int y, const char *str)
{
    while (*str)
    {
        oled_draw_char(x, y, *str);
        x += 6;

        if (x > OLED_WIDTH - 6)
        {
            x = 0;
            y += 8;
        }
        str++;
    }
}

int oled_init(void)
{

    i2c_master_bus_config_t i2c_bus_config = {
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .i2c_port = I2C_MASTER_NUM,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };

    if (i2c_new_master_bus(&i2c_bus_config, &bus_handle) != ESP_OK)
    {
        ESP_LOGE(TAG, "Failed to create I2C bus");
        return -1;
    }

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_I2C_ADDR,
        .scl_speed_hz = I2C_MASTER_FREQ_HZ,
    };

    if (i2c_master_bus_add_device(bus_handle, &dev_cfg, &dev_handle) != ESP_OK)
    {
        ESP_LOGE(TAG, "Failed to add I2C device");
        return -1;
    }

    oled_write_cmd(SSD1306_CMD_DISPLAY_OFF);
    oled_write_cmd(SSD1306_CMD_SET_DISP_CLK_DIV);
    oled_write_cmd(0x80);
    oled_write_cmd(SSD1306_CMD_SET_MUX_RATIO);
    oled_write_cmd(0x1F);
    oled_write_cmd(SSD1306_CMD_SET_DISP_OFFSET);
    oled_write_cmd(0x00);
    oled_write_cmd(SSD1306_CMD_SET_START_LINE | 0x00);
    oled_write_cmd(SSD1306_CMD_CHARGE_PUMP);
    oled_write_cmd(0x14);
    oled_write_cmd(SSD1306_CMD_MEMORY_ADDR_MODE);
    oled_write_cmd(0x02);
    oled_write_cmd(SSD1306_CMD_SEG_REMAP | 0x01);
    oled_write_cmd(SSD1306_CMD_COM_OUT_DIRECTION);
    oled_write_cmd(SSD1306_CMD_SET_COM_PINS);
    oled_write_cmd(0x02);
    oled_write_cmd(SSD1306_CMD_SET_CONTRAST);
    oled_write_cmd(0xCF);
    oled_write_cmd(SSD1306_CMD_SET_PRECHARGE);
    oled_write_cmd(0xF1);
    oled_write_cmd(SSD1306_CMD_SET_VCOMH);
    oled_write_cmd(0x40);
    oled_write_cmd(SSD1306_CMD_NORMAL_DISPLAY);

    oled_clear();
    oled_write_cmd(SSD1306_CMD_DISPLAY_ON);
    ESP_LOGI(TAG, "OLED initialized successfully");
    return 0;
}

void oled_clear(void)
{

    memset(display_buffer, 0, sizeof(display_buffer));

    for (int page = 0; page < OLED_PAGES; page++)
    {
        oled_write_cmd(SSD1306_CMD_PAGE_ADDR);
        oled_write_cmd(page);
        oled_write_cmd(page);
        oled_write_cmd(SSD1306_CMD_COLUMN_ADDR);
        oled_write_cmd(0);
        oled_write_cmd(127);

        oled_write_data(display_buffer[page], OLED_WIDTH);
    }
}

void oled_display_sensor_data(const sensor_data_t *data)
{

    memset(display_buffer, 0, sizeof(display_buffer));

    char line[32];

    snprintf(line, sizeof(line), "Tmp&Hm: %5.1fC %4.1f%%", data->temperature, data->humidity);
    oled_draw_string(0, 0, line);

    const char *light_status = data->light_level >= 50.0f ? "Bright" : "Dark";
    snprintf(line, sizeof(line), "Light: %s", light_status);
    oled_draw_string(0, 8, line);

    const char *rain_status = data->rain_detected ? "Wet" : "Dry";
    snprintf(line, sizeof(line), "Rain: %s", rain_status);
    oled_draw_string(0, 16, line);

    snprintf(line, sizeof(line), "%s", data->time_str);
    oled_draw_string(25, 24, line);

    for (int page = 0; page < OLED_PAGES; page++)
    {

        oled_write_cmd(SSD1306_CMD_PAGE_ADDR);
        oled_write_cmd(page);
        oled_write_cmd(page);

        oled_write_cmd(SSD1306_CMD_COLUMN_ADDR);
        oled_write_cmd(0);
        oled_write_cmd(127);

        oled_write_data(display_buffer[page], OLED_WIDTH);
    }
}

void oled_send_cmd(uint8_t cmd)
{
    oled_write_cmd(cmd);
}

void oled_send_data(const uint8_t *data, uint16_t len)
{
    oled_write_data(data, len);
}
